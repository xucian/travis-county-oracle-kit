#!/usr/bin/env bash
# Refresh this mirror from a kit checkout on branch `travis`.
# usage: oracle/travis/refresh-from-kit.sh /path/to/kit-travis
set -euo pipefail
kit="${1:?kit checkout path}"
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
base="99c7bff"
core='^skills/use-oracle/runtime/(bin/elephant-county\.mjs|\.gitignore)$'
# The list is every file the travis branch added or changed since the pin, minus the two core files
# carried as kit-core.patch, so a new Travis file can never be left out of the mirror.
{
  echo "# Travis-specific files on the kit branch \`travis\`, relative to the kit checkout root."
  echo "# Generated by refresh-from-kit.sh from the branch's diff against $base; do not edit by hand."
  echo "# Plain files are copied verbatim by refresh-from-kit.sh / apply-to-kit.sh; the two kit core files"
  echo "# that carry a two-line Travis registration are applied as the patch kit-core.patch."
  git -C "$kit" diff --name-only --no-renames --diff-filter=AM "$base" HEAD | grep -Ev "$core"
} > "$here/kit-files.txt"
rm -rf "$here/kit"
grep -v '^#' "$here/kit-files.txt" | grep -v '^$' | while read -r rel; do
  mkdir -p "$here/kit/$(dirname "$rel")"
  cp "$kit/$rel" "$here/kit/$rel"
done
# The two kit core files that only gain the Travis registration (ADAPTERS entry, data/ ignore line).
git -C "$kit" diff "$base" -- skills/use-oracle/runtime/bin/elephant-county.mjs skills/use-oracle/runtime/.gitignore > "$here/kit-core.patch"
git -C "$kit" rev-parse HEAD > "$here/KIT_COMMIT"
echo "mirrored $(grep -vc '^#' "$here/kit-files.txt") files from $kit at $(cat "$here/KIT_COMMIT")"
